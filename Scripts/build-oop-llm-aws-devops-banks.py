def pack(pid, title, blurb, group, group_title, rows, prefix):
    questions = []
    for key, text, answer, hints, topic in rows:
        questions.append(item(
            qid=f"{prefix}-{key}", pack=pid, group=group,
            topic=f"{group}-{topic}", title=topic.replace("-", " ").title(),
            text=text, answer=answer, hints=hints,
        ))
    return {
        "packs": [{
            "id": pid, "title": title, "blurb": blurb,
            "groups": [{"id": group, "title": group_title}],
            "questions": questions,
        }],
        "positions": [],
    }


def existing_texts(group: str, skip: set[str]) -> set[str]:
    texts = set()
    for path in OUT.glob("*.json"):
        if path.name in skip:
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        for p in data.get("packs") or []:
            for q in p.get("questions") or []:
                if q.get("groupId") == group:
                    texts.add(" ".join((q.get("text") or "").lower().split()))
    return texts


def drop_dupes(rows, group, skip):
    seen = existing_texts(group, skip)
    out = []
    for row in rows:
        key = " ".join(row[1].lower().split())
        if key in seen:
            continue
        seen.add(key)
        out.append(row)
    return out


